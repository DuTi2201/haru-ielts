class Option(_M):
    id: str  # "1" .. "4"
    text: str | None = None
    scene: Scene | None = None
    chart: Chart | None = None

    @model_validator(mode="after")
    def _something(self) -> "Option":
        if self.text is None and self.scene is None and self.chart is None:
            raise ValueError(f"option {self.id!r} has no text, scene or chart")
        return self


class Question(_M):
    id: str  # unique across the whole bank: L1, R12, …
    prompt_en: str | None = None
    prompt_vi: str | None = None
    options: list[Option] = Field(min_length=2, max_length=5)
    answer: str
    explanation_vi: str
    tags: list[str] = []  # the grammar / vocabulary the question tests

    @model_validator(mode="after")
    def _answer_is_an_option(self) -> "Question":
        ids = [o.id for o in self.options]
        if len(set(ids)) != len(ids):
            raise ValueError(f"question {self.id}: duplicate option ids {ids}")
        if self.answer not in ids:
            raise ValueError(f"question {self.id}: answer {self.answer!r} is not one of {ids}")
        if len(set(self.tags)) != len(self.tags):
            raise ValueError(f"question {self.id}: duplicate tags {self.tags}")  # the tags are list keys in the UI
        return self


class McqExercise(_M):
    id: str
    skill: Literal["listening", "reading"]
    type: str  # e.g. listen_picture, listen_chart, listen_reply, read_cloze, read_order …
    title_vi: str
    instruction_en: str | None = None
    instruction_vi: str | None = None
    stimulus: Stimulus | None = None
    questions: list[Question] = Field(min_length=1)

    @model_validator(mode="after")
    def _stimulus_fits(self) -> "McqExercise":
        if self.skill == "listening" and not isinstance(self.stimulus, AudioStimulus):
            raise ValueError(f"{self.id}: a listening exercise needs an audio stimulus")
        if isinstance(self.stimulus, OrderStimulus):
            for q in self.questions:
                if len(q.options) != 4 or any(o.text is None for o in q.options):
                    raise ValueError(f"{self.id}: ordering questions list the orders as text options")
        return self


