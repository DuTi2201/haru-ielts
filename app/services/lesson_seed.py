class SessionSeed(_M):
    """One sitting ("buổi") of a lesson, planned by hand: what the learner can DO after it, the
    words and cards in the order they are best taught, and the few questions that close it. The
    sittings of a lesson share out its words, cards and questions: each one is in exactly one
    sitting (checked below), so cutting a lesson this way adds, removes and rewords nothing."""

    title_vi: str = Field(min_length=4, max_length=70)
    # "Sau buổi này bạn …": a thing the learner can do, in plain words (one or two sentences)
    can_do_vi: str = Field(min_length=15, max_length=240)
    # where it is used outside the app (a real situation), optional
    use_vi: str | None = Field(default=None, min_length=10, max_length=200)
    # which TOPIK I question form this buys the learner, optional and honest (no promise it does not keep)
    topik_vi: str | None = Field(default=None, min_length=10, max_length=240)
    vocab: list[str] = []  # `headword` of the lesson's words, in the order they are taught
    grammar: list[str] = []  # `pattern` of the lesson's cards, in the order they are taught
    check: list[str] = []  # ids of the lesson's exercises that close the sitting (answer what was just learnt)
    situation: SituationSeed | None = None  # a short dialogue situation (see SituationSeed)
    # the sitting's lecture, written by an editor (lesson_audio.build_authored_lecture): slides in
    # order, each {"kind": title|word|scene|recap|end, …, "lines": [{"say": …} | {"en": …, "gap": bool}]}
    lecture: list[dict] | None = None

    @model_validator(mode="after")
    def _lecture_is_sound(self) -> "SessionSeed":
        words = [s.get("headword") for s in self.lecture or [] if s.get("kind") == "word"]
        for s in self.lecture or []:
            if s.get("kind") not in ("title", "word", "scene", "recap", "end"):
                raise ValueError(f"{self.title_vi}: unknown lecture slide kind {s.get('kind')!r}")
            for ln in s.get("lines") or []:
                if bool(ln.get("say")) == bool(ln.get("en")):
                    raise ValueError(f"{self.title_vi}: a lecture line is either 'say' or 'en': {ln}")
        if self.lecture is not None and sorted(words) != sorted(self.vocab):
            raise ValueError(f"{self.title_vi}: the lecture must teach exactly the sitting's words")
        return self

    @model_validator(mode="after")
    def _not_empty(self) -> "SessionSeed":
        if not (self.vocab or self.grammar or self.check):
            raise ValueError(f"{self.title_vi}: a sitting needs words, cards or questions")
        return self


class LessonSeed(_M):
    slug: str = Field(pattern=r"^[a-z0-9][a-z0-9-]{2,78}$")
    title: str
    title_en: str | None = None
    topic: str
    track: Literal["beginner", "intermediate", "advanced"]
    level: int = Field(ge=1, le=6)
    sort_order: int
    summary: str
    # "review" = the topic's review lesson: no words or cards of its own, a map of the topic's
    # grammar by function, a timed mixed set and a capstone (see ReviewSeed)
    kind: Literal["lesson", "review", "hangul"] = "lesson"
    vocab: list[VocabSeed] = []
    grammar: list[GrammarSeed] = []
    notes: list[NoteSeed] = []
    # Notes for whoever maintains the lesson (what is unverified, where a figure came from).
    # They stay in this file: never written to the database, never sent to the learner,
    # never read out in the lecture.
    editor_notes: list[NoteSeed] = []
    # which practice bank `exercise_ids` are taken from: "" = app/seed/exercises/*.json,
    # "<name>" = app/seed/exercises/<name>/*.json (its own guides, overview, extension)
    bank: str = Field(default="", pattern=r"^[a-z0-9-]*$", max_length=40)
    exercise_ids: list[str] = []
    # at most three real exam questions to try after the practice (a few, so the lesson does not feel heavier)
    topik2: list[Topik2Pick] = Field(default=[], max_length=3)
    review: ReviewSeed | None = None
    # "Việc cần làm" at the top of the lesson screen (optional: a lesson without it shows only the counts)
    coach: CoachSeed | None = None
    # The lesson cut into sittings by hand (empty = the app cuts it evenly): see SessionSeed.
    sessions: list[SessionSeed] = []
    hangul: HangulSeed | None = None  # kind "hangul" only: the five parts of Bảng chữ cái
    # this lesson was cut out of another (scripts/split_foundation.py): the slug it came from. On
    # sync, the words, cards and practice answers it took over are MOVED from that lesson in the
    # database (same rows, same ids), so learners keep their schedules and answers.
    split_from: str | None = Field(default=None, pattern=r"^[a-z0-9][a-z0-9-]{2,78}$")

    @model_validator(mode="after")
    def _coach_has_a_goal(self) -> "LessonSeed":
        if self.coach is not None and not self.coach.goal_vi and not any(n.kind == "goal" for n in self.notes):
            raise ValueError(f"{self.slug}: the coach block needs a `goal_vi` (the lesson has no `goal` note to take it from)")
        return self

    @model_validator(mode="after")
    def _kind_fits(self) -> "LessonSeed":
        if (self.kind == "hangul") != (self.hangul is not None):
            raise ValueError(f"{self.slug}: the `hangul` section goes with kind \"hangul\" (and only with it)")
        if self.kind == "hangul":
            if self.vocab or self.grammar or self.review is not None or self.topik2:
                raise ValueError(f"{self.slug}: the Hangul lesson has no words, cards, review or exam picks of its own")
            if not self.exercise_ids:
                raise ValueError(f"{self.slug}: the Hangul lesson needs its end check (exercise_ids)")
            return self
        if self.kind == "lesson":
            if not self.vocab:
                raise ValueError(f"{self.slug}: a lesson needs at least one word")
            if self.review is not None:
                raise ValueError(f"{self.slug}: only a review lesson has a 'review' section")
        else:
            if self.review is None:
                raise ValueError(f"{self.slug}: a review lesson needs a 'review' section")
            if self.vocab or self.grammar:
                raise ValueError(f"{self.slug}: a review lesson has no words or cards of its own")
            if self.topik2:
                raise ValueError(f"{self.slug}: a review lesson has no TOPIK II picks (it is itself the exam practice)")
            if not self.exercise_ids:
                raise ValueError(f"{self.slug}: a review lesson needs exercises")
        return self

    @model_validator(mode="after")
    def _unique(self) -> "LessonSeed":
        for what, keys in (
            ("vocab headword", [v.headword for v in self.vocab]),
            ("grammar pattern", [g.pattern for g in self.grammar]),
            ("exercise id", self.exercise_ids),
            ("TOPIK II question", [p.qid for p in self.topik2]),
        ):
            dupes = sorted({k for k in keys if keys.count(k) > 1})
            if dupes:
                raise ValueError(f"{self.slug}: duplicate {what}: {dupes}")
        return self

    @model_validator(mode="after")
    def _sessions_share_out_the_lesson(self) -> "LessonSeed":
        """Every word and card in exactly one sitting; a closing question in at most one, and only
        one of this lesson's own."""
        if not self.sessions:
            return self
        if self.kind != "lesson":
            raise ValueError(f"{self.slug}: only a lesson with words and cards is cut into sittings")
        for what, have, used in (
            ("word", [v.headword for v in self.vocab], [w for x in self.sessions for w in x.vocab]),
            ("card", [g.pattern for g in self.grammar], [w for x in self.sessions for w in x.grammar]),
        ):
            missing = [k for k in have if k not in used]
            extra = [k for k in used if k not in have]
            dupes = sorted({k for k in used if used.count(k) > 1})
            if missing or extra or dupes:
                raise ValueError(f"{self.slug}: sittings must hold every {what} exactly once: missing {missing[:5]}, unknown {extra[:5]}, repeated {dupes[:5]}")
        checks = [i for x in self.sessions for i in x.check]
        bad = [i for i in checks if i not in self.exercise_ids]
        dupes = sorted({i for i in checks if checks.count(i) > 1})
        if bad or dupes:
            raise ValueError(f"{self.slug}: sitting checks must be this lesson's exercises, each once: unknown {bad[:5]}, repeated {dupes[:5]}")
        return self


