# ---------------------------------------------------------------- the Hangul lesson --
# "Bảng chữ cái" (kind "hangul"): five parts that teach the letters, the syllable block, the
# final consonant (patchim) and the sound changes Nền tảng 1 relies on, each with the words of
# Nền tảng 1 a learner can already read at that point. Checked here: a part's reading words use
# only the letters taught up to it (finals only from the patchim part on).
JAMO_INITIAL = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
JAMO_MEDIAL = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
JAMO_FINAL = ["", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ", "ㄻ", "ㄼ", "ㄽ", "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ",
              "ㅅ", "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ"]


def jamo_of(syllable: str) -> tuple[str, str, str] | None:
    """(initial, medial, final) of one Hangul syllable ("" when it has no final), else None."""
    c = ord(syllable) - 0xAC00
    if not 0 <= c < 11172:
        return None
    return JAMO_INITIAL[c // 588], JAMO_MEDIAL[(c % 588) // 28], JAMO_FINAL[c % 28]


