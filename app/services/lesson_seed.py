class BuildOrder(_M):
    """Rung 1 of "Tạo câu": put word tiles in order to make one sentence. Korean word order is
    freer than Vietnamese, so every acceptable order is listed. A tile that no answer uses is a
    distractor (a wrong ending, a wrong particle): it tests the pattern the lesson teaches."""

    id: str
    skill: Literal["build"]
    type: Literal["build_order"]
    rung: Literal[1]
    title_vi: str
    instruction_vi: str | None = None
    situation_vi: str | None = None
    meaning_vi: str  # what the sentence has to say, in Vietnamese
    tiles: list[str] = Field(min_length=2)  # as shown (already shuffled), distractors included
    answers: list[str] = Field(min_length=1)  # accepted orders, tiles joined by one space; the first is the model
    explain_vi: str | None = None
    common_errors_vi: list[str] = []

    @model_validator(mode="after")
    def _tiles_make_the_answers(self) -> "BuildOrder":
        if len(set(self.answers)) != len(self.answers):
            raise ValueError(f"{self.id}: the same answer twice")
        words = [a.split(" ") for a in self.answers]
        for a, w in zip(self.answers, words):
            if " ".join(w) != a or any(not t for t in w):
                raise ValueError(f"{self.id}: answer {a!r} must be tiles joined by single spaces")
        from collections import Counter

        used = Counter(words[0])
        for a, w in zip(self.answers, words):
            if Counter(w) != used:
                raise ValueError(f"{self.id}: answer {a!r} does not use the same tiles as {self.answers[0]!r}")
        extra = Counter(self.tiles) - used
        if Counter(self.tiles) - extra != used:
            raise ValueError(f"{self.id}: the tiles {self.tiles} do not contain every word of the answer {self.answers[0]!r}")
        if " ".join(self.tiles) in self.answers:
            raise ValueError(f"{self.id}: the tiles are shown already in an accepted order")
        if len(self.tiles) > 10:
            raise ValueError(f"{self.id}: more than 10 tiles do not fit a phone screen")
        return self


class Gloss(_M):
    ko: str
    vi: str


class Dictation(_M):
    """Chép chính tả: the learner hears a short script and types it, line by line. The point is to
    get the ear used to the speed of the exam, not to be perfect, so a script is short (at most
    four lines) and a lesson holds only a few. Afterwards the learner listens again with the script
    and its meaning in front of them and learns `focus`, the words that were missed."""

    id: str
    skill: Literal["listening"]
    type: Literal["listen_dictation"]
    title_vi: str
    instruction_vi: str | None = None
    stimulus: AudioStimulus
    focus: list[Gloss] = Field(min_length=2, max_length=8)  # words and forms to learn after the dictation
    tips_vi: list[str] = []

    @model_validator(mode="after")
    def _short_and_explained(self) -> "Dictation":
        turns = self.stimulus.turns
        if len(turns) > 4:
            raise ValueError(f"{self.id}: a dictation has at most 4 lines")
        if any(not t.vi for t in turns):
            raise ValueError(f"{self.id}: every line needs its meaning (`vi`): it is shown after the check")
        if sum(len(re.sub(r"\s", "", t.text)) for t in turns) > 130:
            raise ValueError(f"{self.id}: a dictation script is at most about 130 characters")
        return self


