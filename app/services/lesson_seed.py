def card_forms(headword: str) -> set[str]:
    """The dictionary forms a card teaches: `이사(하다)` -> 이사, 이사하다; `늘 · 항상` -> 늘, 항상."""
    out: set[str] = set()
    for part in re.split(r"\s*(?:·|/|,)\s*", headword):
        p = re.sub(r"\s+", " ", part.strip())
        if not p:
            continue
        out.add(p)
        m = re.fullmatch(r"(.+?)\((?:을 |를 )?(하다|되다|이다)\)", p)
        if m:
            out |= {m.group(1), m.group(1) + m.group(2)}
        out.add(re.sub(r"\(.*?\)", "", p).strip())
    return out


def nikl_coverage(lessons: list["ResolvedLesson"], path: Path = NIKL_FILE) -> tuple[dict[str, Any], list[str]]:
    """How many NIKL beginner words (한국어기초사전 초급) the course teaches as cards, and — when the
    list is enforced — a problem for every one it does not teach and does not explain in `not_taught`."""
    if not path.exists():
        return {}, []
    data = _read(path)
    taught: set[str] = set()
    for r in lessons:
        for v in r.seed.vocab:
            taught |= card_forms(v.headword)
    words = [e["w"] for e in data["words"]]
    missing = [w for w in words if w not in taught]
    excused = data.get("not_taught", {})
    report = {"words": len(words), "taught": len(words) - len(missing), "missing": len(missing), "excused": len(excused)}
    problems = []
    if data.get("enforce"):
        problems = [f"NIKL 초급 word {w!r} is not a card of any lesson (teach it, or say why in not_taught)" for w in missing if w not in excused]
    problems += [f"not_taught lists {w!r}, which is not a NIKL 초급 word" for w in excused if w not in set(words)]
    return report, problems


