_EXERCISE_BY_TYPE: dict[str, type[BaseModel]] = {
    "build_order": BuildOrder, "write_fill": WriteFill, "write_essay": WriteEssay, "speak": Speak,
    "listen_dictation": Dictation,
}


def _read(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _validate_exercise(raw: dict[str, Any], skill: str) -> dict[str, Any]:
    kind = raw.get("type")
    model: type[BaseModel] = _EXERCISE_BY_TYPE.get(str(kind), McqExercise)
    ex = model.model_validate(raw)
    if getattr(ex, "skill") != skill:
        raise ValueError(f"{raw.get('id')}: skill {getattr(ex, 'skill')!r} in a {skill} file")
    return ex.model_dump(mode="json", exclude_none=True)


def _question_ids(ex: dict[str, Any]) -> list[str]:
    """The ids a learner's answers are filed under (see LessonExerciseResult)."""
    if ex["type"] == "write_fill":
        return [f"{ex['id']}:{b['id']}" for b in ex["blanks"]]
    if ex["type"] in ("write_essay", "speak", "build_order", "listen_dictation"):
        return [ex["id"]]
    return [q["id"] for q in ex["questions"]]


def question_ids(ex: dict[str, Any]) -> list[str]:
    """The ids a learner's answers to this exercise are filed under (public name of the helper)."""
    return _question_ids(ex)


def question_index(practice: dict[str, Any] | None) -> dict[str, dict[str, Any]]:
    """question id -> the exercise it belongs to, for one lesson's `practice`."""
    index: dict[str, dict[str, Any]] = {}
    for ex in (practice or {}).get("items", []):
        for qid in _question_ids(ex):
            index[qid] = ex
    return index


def load_exercise_bank(
    exercise_dir: Path = EXERCISE_DIR, seen_question_ids: dict[str, str] | None = None
) -> tuple[dict[str, dict[str, Any]], dict[str, Any], list[str]]:
    """(exercises by id, per-skill guides + overview + extension, problems) of ONE folder.
    `seen_question_ids` lets several banks share one registry of question ids."""
    problems: list[str] = []
    exercises: dict[str, dict[str, Any]] = {}
    shared: dict[str, Any] = {"guides": {}, "overview": None, "extension": None, "links": {}}
    if seen_question_ids is None:
        seen_question_ids = {}
    if not exercise_dir.is_dir():
        return exercises, shared, [f"{exercise_dir} does not exist"]
    for path in sorted(exercise_dir.glob("*.json")):
        try:
            data = _read(path)
            if path.stem == "overview":
                shared["overview"] = Overview.model_validate(data).model_dump(mode="json", exclude_none=True)
                continue
            if path.stem == "extension":
                shared["extension"] = Extension.model_validate(data).model_dump(mode="json", exclude_none=True)
                continue
            if path.stem == "grammar_links":
                shared["links"] = GrammarLinks.model_validate(data).links
                continue
            bank = SkillBank.model_validate(data)
        except (ValidationError, ValueError) as exc:
            problems.append(f"{path.name}: {exc}")
            continue
        shared["guides"][bank.skill] = [g.model_dump(mode="json", exclude_none=True) for g in bank.guide]
        for raw in bank.items:
            try:
                ex = _validate_exercise(raw, bank.skill)
            except (ValidationError, ValueError) as exc:
                problems.append(f"{path.name} {raw.get('id', '?')}: {exc}")
                continue
            if ex["id"] in exercises:
                problems.append(f"{path.name}: exercise id {ex['id']} is used twice")
                continue
            for qid in _question_ids(ex):
                if qid in seen_question_ids:
                    problems.append(f"{path.name}: question id {qid} already used by {seen_question_ids[qid]}")
                seen_question_ids[qid] = ex["id"]
            exercises[ex["id"]] = ex
    known = {qid for ex in exercises.values() for qid in _question_ids(ex)} | set(exercises)
    for key in shared["links"]:
        if key not in known:
            problems.append(f"grammar_links.json: {key!r} is neither a question nor an exercise of this bank")
    return exercises, shared, problems


def load_exercise_banks(
    exercise_dir: Path = EXERCISE_DIR,
) -> tuple[dict[str, dict[str, Any]], dict[str, str], dict[str, dict[str, Any]], list[str]]:
    """Every bank: the folder itself ("") and each sub-folder (by name). Returns
    (all exercises by id, bank of each exercise id, shared guides by bank, problems).
    An exercise id or a question id may not be used twice anywhere, so answers never mix
    between banks."""
    exercises: dict[str, dict[str, Any]] = {}
    bank_of: dict[str, str] = {}
    shared_by_bank: dict[str, dict[str, Any]] = {}
    problems: list[str] = []
    seen_question_ids: dict[str, str] = {}
    folders: list[tuple[str, Path]] = [("", exercise_dir)]
    if exercise_dir.is_dir():
        folders += [(p.name, p) for p in sorted(exercise_dir.iterdir()) if p.is_dir() and not p.name.startswith((".", "_"))]
    for name, folder in folders:
        found, shared, issues = load_exercise_bank(folder, seen_question_ids)
        problems += [f"{name}/{i}" if name else i for i in issues]
        shared_by_bank[name] = shared
        for ex_id, ex in found.items():
            if ex_id in exercises:
                problems.append(f"{name or '.'}: exercise id {ex_id} is also used in bank {bank_of[ex_id] or '.'!r}")
                continue
            exercises[ex_id] = ex
            bank_of[ex_id] = name
    return exercises, bank_of, shared_by_bank, problems


def _lesson_hash(seed: LessonSeed, practice: dict[str, Any] | None) -> str:
    blob = json.dumps(
        {"seed": seed.model_dump(mode="json"), "practice": practice}, ensure_ascii=False, sort_keys=True
    )
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def card_info(seed: LessonSeed, g: GrammarSeed) -> dict[str, Any]:
    """What the "grammar in this sentence" box shows about a card (see `_practice_for`)."""
    tier = grammar_tier(g.usage_context_vi)[0]
    info: dict[str, Any] = {
        "pattern": g.pattern,
        "meaning_vi": g.meaning_vi,
        "tier": tier,
        "use_level": effective_use_level(g.usage_context_vi, g.use_level),
        "lesson_slug": seed.slug,
        "lesson_title": seed.title,
        "lesson_order": seed.sort_order,
    }
    first_en = next((ln.strip() for ln in (g.example_en or "").split("\n") if ln.strip()), None)
    if first_en:
        info["example_en"] = first_en
        vi_lines = [ln.strip() for ln in (g.example_vi or "").split("\n") if ln.strip()]
        ko_lines = [ln.strip() for ln in (g.example_en or "").split("\n") if ln.strip()]
        if len(vi_lines) == len(ko_lines):
            info["example_vi"] = vi_lines[0]
    if g.contrasts:
        info["contrast"] = {"pattern": g.contrasts[0].pattern, "diff_vi": g.contrasts[0].diff_vi}
    if g.builds_on:
        info["builds_on"] = list(g.builds_on)
    if g.importance:
        info["importance"] = g.importance
    return info


def grammar_cards_by_bank(seeds: list[LessonSeed]) -> tuple[dict[str, dict[str, dict[str, Any]]], list[str]]:
    """bank -> pattern -> card info, over every lesson of the bank. A pattern may be
    written by one lesson of a bank only, so a link names exactly one card."""
    cards: dict[str, dict[str, dict[str, Any]]] = {}
    problems: list[str] = []
    for seed in seeds:
        bank = cards.setdefault(seed.bank, {})
        for g in seed.grammar:
            if g.pattern in bank:
                problems.append(
                    f"{seed.slug}: grammar pattern {g.pattern!r} is also in {bank[g.pattern]['lesson_slug']} "
                    "(a bank's grammar_links need each pattern to be in one lesson only)"
                )
                continue
            bank[g.pattern] = card_info(seed, g)
    return cards, problems


def graph_problems(seeds: list[LessonSeed]) -> list[str]:
    """The cards' links across the whole curriculum: each `builds_on` names a card taught
    earlier, and every core card says how much of it a learner must keep."""
    ordered = sorted(seeds, key=lambda s: (TRACKS.index(s.track), s.sort_order))
    cards: list[GraphCard] = []
    problems: list[str] = []
    for place, seed in enumerate(ordered):
        for g in seed.grammar:
            cards.append(GraphCard((seed.slug, g.pattern), place, g.pattern, tuple(g.builds_on)))
            extension = grammar_tier(g.usage_context_vi)[0] == "extension"
            if extension and g.importance:
                problems.append(f"{seed.slug}: {g.pattern!r} is an extension card: its level is `use_level`, not `importance`")
            if not extension and not g.importance:
                problems.append(f"{seed.slug}: {g.pattern!r} has no importance (must | normal)")
    problems += [f"grammar links: {p}" for p in resolve_graph(cards)[1]]
    first_place: dict[str, int] = {}
    for place, seed in enumerate(ordered):
        for g in seed.grammar:
            first_place.setdefault(g.pattern, place)
    for place, seed in enumerate(ordered):
        for g in seed.grammar:
            if g.revisits and not (g.revisits in first_place and first_place[g.revisits] < place):
                problems.append(f"{seed.slug}: {g.pattern!r} revisits {g.revisits!r}, which is not a card of an earlier lesson")
    return problems


def question_grammar(ex: dict[str, Any], question_id: str) -> list[str]:
    """The grammar patterns a practice question is linked to (empty when none)."""
    if ex["type"] in NON_MCQ_TYPES:
        return list(ex.get("grammar") or [])
    for q in ex.get("questions") or []:
        if q["id"] == question_id:
            return list(q.get("grammar") or [])
    return []


def _review_problems(seed: LessonSeed, items: list[dict[str, Any]], cards: dict[str, dict[str, Any]]) -> list[str]:
    """Everything a review lesson says about the topic is checked against the real cards and
    exercises: a map that names a pattern the topic does not teach would only mislead."""
    r = seed.review
    assert r is not None
    name = seed.slug
    out: list[str] = []
    where: dict[str, str] = {}
    for f in r.functions:
        dupes = sorted({p for p in f.patterns if f.patterns.count(p) > 1})
        if dupes:
            out.append(f"{name}: function {f.id} lists {dupes} twice")
        for p in f.patterns:
            if p not in cards:
                out.append(f"{name}: function {f.id}: {p!r} is not a grammar card of the bank")
            elif where.setdefault(p, f.id) != f.id:
                out.append(f"{name}: {p!r} is in functions {where[p]} and {f.id} (a card belongs to one function)")
        for rule in f.rules:
            for p in rule.use:
                if p not in cards:
                    out.append(f"{name}: function {f.id}: rule {rule.when_vi[:30]!r} -> {p!r} is not a grammar card of the bank")
    missing = sorted(set(cards) - set(where))
    if missing:
        out.append(f"{name}: cards that are in no function: {missing}")
    if len({f.id for f in r.functions}) != len(r.functions):
        out.append(f"{name}: two functions have the same id")

    by_id = {it["id"]: it for it in items}
    mcq = [it for it in items if it["type"] not in NON_MCQ_TYPES]
    n_questions = sum(len(it["questions"]) for it in mcq)
    if n_questions < 5:
        out.append(f"{name}: a review lesson needs at least 5 multiple-choice questions for its mock set (has {n_questions})")
    if r.mock.bands[-1].min_correct > n_questions:
        out.append(f"{name}: the mock set has {n_questions} questions but a band starts at {r.mock.bands[-1].min_correct}")
    if r.mock.score is not None:
        listening = sum(len(it["questions"]) for it in mcq if it["skill"] == "listening")
        reading = sum(len(it["questions"]) for it in mcq if it["skill"] == "reading")
        if (r.mock.score.listening, r.mock.score.reading) != (listening, reading):
            out.append(
                f"{name}: mock.score says {r.mock.score.listening} listening + {r.mock.score.reading} reading "
                f"but the lesson holds {listening} + {reading}"
            )
        if listening + reading != n_questions:
            out.append(f"{name}: the mock holds multiple-choice questions that are neither listening nor reading")

    cap = r.capstone
    essay, speak = by_id.get(cap.essay_id), by_id.get(cap.speak_id)
    if essay is None or essay["type"] != "write_essay":
        out.append(f"{name}: capstone essay_id {cap.essay_id!r} is not a write_essay of this lesson")
    if speak is None or speak["type"] != "speak":
        out.append(f"{name}: capstone speak_id {cap.speak_id!r} is not a speak task of this lesson")
    patterns = [d.pattern for d in cap.required]
    if len(set(patterns)) != len(patterns):
        out.append(f"{name}: capstone lists a pattern twice")
    for d in cap.required:
        if d.pattern not in cards:
            out.append(f"{name}: capstone detector {d.pattern!r} is not a grammar card of the bank")
    if cap.min_required > len(cap.required):
        out.append(f"{name}: capstone wants {cap.min_required} patterns but lists {len(cap.required)}")
    # the model answers must themselves use what the capstone asks for
    for kind, ex in (("essay", essay), ("speak", speak)):
        text = (ex or {}).get("model_answer_en") or ""
        if not text:
            continue
        hit = [d.pattern for d in cap.required if re.search(d.regex, text, re.S)]
        if len(hit) < cap.min_required:
            out.append(f"{name}: the model answer of the {kind} uses only {len(hit)} of the required patterns {hit}")
    return out


def _detector_problems(seed: LessonSeed, items: list[dict[str, Any]], cards: dict[str, dict[str, Any]]) -> list[str]:
    """A paragraph task that lists patterns to use (`detectors`): each is a card the learner has met,
    and the model answer itself must show every one (otherwise the sample would contradict the list)."""
    out: list[str] = []
    for it in items:
        dets = it.get("detectors") or []
        if not dets:
            continue
        patterns = [d["pattern"] for d in dets]
        if len(set(patterns)) != len(patterns):
            out.append(f"{seed.slug}: {it['id']}: a detector pattern twice")
        for d in dets:
            card = cards.get(d["pattern"])
            if card is None:
                out.append(f"{seed.slug}: {it['id']}: detector {d['pattern']!r} is not a grammar card of the bank")
            elif card["lesson_order"] > seed.sort_order:
                out.append(f"{seed.slug}: {it['id']}: detector {d['pattern']!r} is a card of a later lesson")
        model = it.get("model_answer_en") or ""
        for d in dets:
            if model and not re.search(d["regex"], model, re.S):
                out.append(f"{seed.slug}: {it['id']}: the model answer does not show {d['pattern']!r} (regex {d['regex']!r})")
    return out


def course_position(seed: LessonSeed) -> tuple[int, int]:
    """Where a lesson sits in the course: tracks in order, then sort_order inside the track."""
    return (TRACKS.index(seed.track), seed.sort_order)


def taught_at(seeds: list[LessonSeed]) -> dict[str, tuple[int, int]]:
    """Every vocabulary `headword` and grammar `pattern` of the course -> the earliest lesson that
    teaches it (as a course position). Any bank counts: the course is one path."""
    first: dict[str, tuple[int, int]] = {}
    for seed in seeds:
        pos = course_position(seed)
        for key in [v.headword for v in seed.vocab] + [g.pattern for g in seed.grammar]:
            if key not in first or pos < first[key]:
                first[key] = pos
    return first


def _uses_problems(seed: LessonSeed, items: list[dict[str, Any]], first: dict[str, tuple[int, int]]) -> list[str]:
    """The output contract (`uses`): every listed piece is in the model answer and is taught by
    this lesson or an earlier one."""
    out: list[str] = []
    here = course_position(seed)
    for it in items:
        model = it.get("model_answer_en") or ""
        for ref in it.get("uses") or []:
            if ref["form"] not in model:
                out.append(f"{seed.slug}: {it['id']}: uses {ref['form']!r}, which is not in the model answer")
            pos = first.get(ref["card"])
            if pos is None:
                out.append(f"{seed.slug}: {it['id']}: {ref['form']!r} -> {ref['card']!r} is not a card of any lesson")
            elif pos > here:
                out.append(f"{seed.slug}: {it['id']}: {ref['form']!r} -> {ref['card']!r} is taught only in a later lesson")
    return out


def _practice_for(
    seed: LessonSeed,
    exercises: dict[str, dict[str, Any]],
    shared: dict[str, Any],
    cards: dict[str, dict[str, Any]] | None = None,
) -> dict[str, Any] | None:
    if not seed.exercise_ids:
        return None
    links: dict[str, list[str]] = shared.get("links") or {}
    cards = cards or {}
    items = [copy.deepcopy(exercises[i]) for i in seed.exercise_ids]  # copies: each lesson tags its own
    used: dict[str, dict[str, Any]] = {}

    def tag(owner: dict[str, Any], *keys: str) -> None:
        patterns = next((links[k] for k in keys if k in links), None)
        # a card of a LATER lesson is not offered here: the learner has not met it yet, and a
        # wrong answer must not put an unseen card into their review queue
        patterns = [p for p in patterns or [] if p in cards and cards[p]["lesson_order"] <= seed.sort_order]
        if not patterns:
            return
        owner["grammar"] = patterns
        for pattern in patterns:
            used[pattern] = cards[pattern]

    for it in items:
        if it["type"] in NON_MCQ_TYPES:
            tag(it, it["id"])
        else:
            for q in it["questions"]:
                tag(q, q["id"], it["id"])
    skills = sorted({it["skill"] for it in items}, key=SKILL_ORDER.index)
    by_skill: dict[str, int] = {s: 0 for s in skills}
    for it in items:
        by_skill[it["skill"]] += len(_question_ids(it))
    practice: dict[str, Any] = {
        # what the lesson list shows without shipping the whole set
        "counts": {"items": len(items), "questions": sum(by_skill.values()), "by_skill": by_skill},
        "items": items,
        "guides": {s: shared["guides"].get(s, []) for s in skills},
    }
    if used:
        practice["grammar"] = used  # pattern -> card info, for the box under each answer
    if shared["overview"]:
        practice["overview"] = shared["overview"]
    if shared["extension"]:
        practice["extension"] = shared["extension"]
    if seed.topik2:
        # only the picks: the questions are in the real-exam bank, which is served behind login
        practice["topik2"] = [p.model_dump(mode="json") for p in seed.topik2]
    if seed.review is not None:
        review = seed.review.model_dump(mode="json", exclude_none=True)
        shown = {p for f in seed.review.functions for p in f.patterns}
        shown |= {p for f in seed.review.functions for rule in f.rules for p in rule.use}
        review["cards"] = {p: cards[p] for p in sorted(shown) if p in cards}
        review["mock"]["question_ids"] = [q["id"] for it in items if it["type"] not in NON_MCQ_TYPES for q in it["questions"]]
        practice["kind"] = "review"
        practice["review"] = review
    if seed.hangul is not None:
        practice["kind"] = "hangul"
        practice["hangul"] = seed.hangul.model_dump(mode="json", exclude_none=True)
    # Vừa sức / Thử thách and the first meeting of each question type (measured offline)
    from app.services import practice_tiers

    practice_tiers.apply(seed.slug, practice)
    return practice


def load_all(seed_dir: Path = SEED_DIR) -> SeedBundle:
    exercises, bank_of, shared_by_bank, problems = load_exercise_banks(seed_dir / "exercises")
    lessons: list[ResolvedLesson] = []
    lesson_dir = seed_dir / "lessons"
    if not lesson_dir.is_dir():
        problems.append(f"{lesson_dir} does not exist")
        return SeedBundle(lessons=[], exercises=exercises, problems=problems)
    slugs: set[str] = set()
    orders: dict[tuple[str, int], str] = {}
    used: set[str] = set()
    seeds: list[LessonSeed] = []
    for path in sorted(lesson_dir.glob("*.json")):
        try:
            seed = LessonSeed.model_validate(_read(path))
        except (ValidationError, ValueError) as exc:
            problems.append(f"{path.name}: {exc}")
            continue
        if seed.slug in slugs:
            problems.append(f"{path.name}: slug {seed.slug} is used twice")
            continue
        slugs.add(seed.slug)
        key = (seed.track, seed.sort_order)
        if key in orders:
            problems.append(f"{path.name}: sort_order {seed.sort_order} of track {seed.track} is also {orders[key]}")
        orders[key] = seed.slug
        if seed.bank not in shared_by_bank:
            problems.append(f"{path.name}: unknown practice bank {seed.bank!r} (no folder app/seed/exercises/{seed.bank}/)")
            continue
        missing = [i for i in seed.exercise_ids if i not in exercises or bank_of[i] != seed.bank]
        if missing:
            problems.append(f"{path.name}: unknown exercise ids {missing} (in bank {seed.bank or '.'!r})")
            continue
        seeds.append(seed)

    cards, card_problems = grammar_cards_by_bank(seeds)
    problems += card_problems
    problems += graph_problems(seeds)
    for bank, shared in shared_by_bank.items():
        for key, patterns in shared["links"].items():
            for pattern in patterns:
                if pattern not in cards.get(bank, {}):
                    problems.append(
                        f"grammar_links.json of bank {bank or '.'!r}: {key} -> {pattern!r} is not a grammar card of any lesson of the bank"
                    )

    first = taught_at(seeds)
    for seed in seeds:
        used.update(seed.exercise_ids)
        problems += _uses_problems(seed, [exercises[i] for i in seed.exercise_ids], first)
        if seed.review is not None:
            problems += _review_problems(seed, [exercises[i] for i in seed.exercise_ids], cards.get(seed.bank, {}))
        problems += _detector_problems(seed, [exercises[i] for i in seed.exercise_ids], cards.get(seed.bank, {}))
        practice = _practice_for(seed, exercises, shared_by_bank[seed.bank], cards.get(seed.bank, {}))
        lessons.append(ResolvedLesson(seed=seed, practice=practice, content_hash=_lesson_hash(seed, practice)))
    unused = sorted(set(exercises) - used)
    if unused and lessons:
        problems.append(f"exercises not placed in any lesson: {unused}")
    lessons.sort(key=lambda r: (TRACKS.index(r.seed.track), r.seed.sort_order))
    return SeedBundle(lessons=lessons, exercises=exercises, problems=problems)


def lesson_text(seed: LessonSeed) -> str:
    """`Lesson.content`: the plain-text body older code paths still read."""
    parts = [seed.summary.strip()]
    for n in seed.notes:
        parts.append(((n.title + ": ") if n.title else "") + n.body.strip())
    return "\n\n".join(p for p in parts if p)


