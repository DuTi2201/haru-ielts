class GrammarLinks(_M):
    """grammar_links.json of a bank: which grammar cards each question is built to test.

    Key = a question id (one question) or an exercise id (every question of it — the way
    to link a write_fill, write_essay or speak item); value = the `pattern` of the cards,
    exactly as the lesson writes it, the main one first. A wrong answer sends the main
    card (and the others) back to the learner's review queue; a right answer touches
    nothing. Only list what the question really tests, not the distractors."""

    links: dict[str, list[str]]

    @model_validator(mode="after")
    def _non_empty(self) -> "GrammarLinks":
        for key, patterns in self.links.items():
            if not patterns:
                raise ValueError(f"{key}: an empty list of cards (leave the question out instead)")
            if len(set(patterns)) != len(patterns):
                raise ValueError(f"{key}: the same card twice")
        return self


