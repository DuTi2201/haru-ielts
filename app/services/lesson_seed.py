def shift_lessons(by: int, lesson_dir: Path = LESSON_DIR) -> int:
    """Move every lesson file `by` places (`"sort_order": n` -> n + by), keeping each file's own
    layout. Used once, with the Hangul lesson that goes in front of Nền tảng 1 (and with
    billing.catalog.LESSON_SHIFT in the same commit). Returns how many files moved."""
    pattern = re.compile(r'^(\s*"sort_order":\s*)(\d+)', re.M)
    moved = 0
    for path in sorted(lesson_dir.glob("*.json")):
        text = path.read_text(encoding="utf-8")
        new, n = pattern.subn(lambda m: f"{m.group(1)}{int(m.group(2)) + by}", text, count=1)
        if n:
            path.write_text(new, encoding="utf-8")
            moved += 1
    return moved


