def sync_lessons(db: Any, bundle: SeedBundle | None = None) -> dict[str, str]:
    """Write the seed to the database (sync Session). Returns {slug: created |
    updated | unchanged}. Safe to run on every start: an unchanged lesson costs
    one SELECT. Nothing is written when the files have problems."""
    from sqlalchemy import delete, or_, select

    from app.models import (
        ErrorLog,
        GrammarCompetency,
        GrammarPoint,
        ItemState,
        Lesson,
        LessonTopic,
        Topic,
        VocabItem,
        VocabItemAudio,
    )

    bundle = bundle or load_all()
    if bundle.problems:
        raise ValueError("lesson seed has problems:\n- " + "\n- ".join(bundle.problems))

    report: dict[str, str] = {}
    _rehome_split(db, bundle)
    for resolved in bundle.lessons:
        seed = resolved.seed
        lesson = db.execute(select(Lesson).where(Lesson.slug == seed.slug)).scalar_one_or_none()
        if lesson is not None and lesson.content_hash == resolved.content_hash:
            report[seed.slug] = "unchanged"
            continue
        status = "updated" if lesson is not None else "created"
        if lesson is None:
            lesson = Lesson(slug=seed.slug, content_hash=resolved.content_hash, title=seed.title, level=seed.level, content="")
            db.add(lesson)
        lesson.content_hash = resolved.content_hash
        lesson.title = seed.title
        lesson.title_en = seed.title_en
        lesson.level = seed.level
        lesson.track = seed.track
        lesson.sort_order = seed.sort_order
        lesson.summary = seed.summary
        lesson.content = lesson_text(seed)
        lesson.notes = [n.model_dump(mode="json", exclude_none=True) for n in seed.notes]
        lesson.coach = seed.coach.model_dump(mode="json", exclude_none=True) if seed.coach else None
        lesson.sessions = [x.model_dump(mode="json", exclude_none=True) for x in seed.sessions] or None
        lesson.practice = resolved.practice
        db.flush()

        topic = db.execute(select(Topic).where(Topic.name == seed.topic)).scalar_one_or_none()
        if topic is None:
            topic = Topic(name=seed.topic)
            db.add(topic)
            db.flush()
        # a lesson file names its one topic; a lesson that moved topic leaves the old one behind
        for link in db.execute(select(LessonTopic).where(LessonTopic.lesson_id == lesson.id, LessonTopic.topic_id != topic.id)).scalars():
            db.delete(link)
        if db.get(LessonTopic, (lesson.id, topic.id)) is None:
            db.add(LessonTopic(lesson_id=lesson.id, topic_id=topic.id))

        # ---- vocabulary: by headword, so an edit keeps the id (and the learner's schedule)
        have_v = {v.headword: v for v in db.execute(select(VocabItem).where(VocabItem.lesson_id == lesson.id)).scalars()}
        for item in seed.vocab:
            row = have_v.pop(item.headword, None) or VocabItem(lesson_id=lesson.id, headword=item.headword, level=seed.level)
            row.pos = POS_LABEL[item.pos]
            row.meaning_vi = item.meaning_vi
            row.level = seed.level
            row.usage_note_vi = item.note_vi
            row.pron_en = item.pron
            row.example_en = item.example_en
            row.example_vi = item.example_vi
            row.family = item.family
            row.exam = item.exam
            row.priority = item.priority
            row.hanja = item.hanja
            row.sino_vietnamese = item.sino_vietnamese
            row.collocations = [c.model_dump(mode="json") for c in item.collocations] or None
            if row.id is None:
                db.add(row)
        gone_v = [v.id for v in have_v.values()]
        if gone_v:
            db.execute(delete(ItemState).where(ItemState.item_type == "vocab_item", ItemState.item_id.in_(gone_v)))
            db.execute(delete(ErrorLog).where(ErrorLog.item_type == "vocab_item", ErrorLog.item_id.in_(gone_v)))
            db.execute(delete(VocabItemAudio).where(VocabItemAudio.vocab_item_id.in_(gone_v)))
            db.execute(delete(VocabItem).where(VocabItem.id.in_(gone_v)))

        # ---- grammar: by pattern
        have_g = {g.pattern: g for g in db.execute(select(GrammarPoint).where(GrammarPoint.lesson_id == lesson.id)).scalars()}
        for pos, item in enumerate(seed.grammar):
            row = have_g.pop(item.pattern, None) or GrammarPoint(lesson_id=lesson.id, pattern=item.pattern, level=seed.level)
            row.meaning_vi = item.meaning_vi
            row.level = seed.level
            row.position = pos
            row.check_item = item.check.model_dump(mode="json") if item.check else None
            row.usage_context_vi = item.usage_context_vi
            row.note_vi = item.note_vi
            row.exam_tip_vi = item.exam_tip_vi
            row.example_en = item.example_en
            row.example_vi = item.example_vi
            row.exam = item.exam
            row.use_level = item.use_level
            row.builds_on = list(item.builds_on) or None
            row.revisits = item.revisits
            row.importance = item.importance
            row.contrasts = [c.model_dump(mode="json") for c in item.contrasts] or None
            row.contrast_group = None
            if row.id is None:
                db.add(row)
        gone_g = [g.id for g in have_g.values()]
        if gone_g:
            db.execute(delete(ItemState).where(ItemState.item_type == "grammar_point", ItemState.item_id.in_(gone_g)))
            db.execute(delete(ErrorLog).where(ErrorLog.item_type == "grammar_point", ErrorLog.item_id.in_(gone_g)))
            db.execute(delete(GrammarCompetency).where(GrammarCompetency.grammar_id.in_(gone_g)))
            db.execute(delete(GrammarPoint).where(GrammarPoint.id.in_(gone_g)))
        report[seed.slug] = status
    db.commit()
    from app.services import feathers  # (imports this module)

    feathers.reset_cache()  # the lessons' feathers are cut again from what was just written
    return report


def _rehome_split(db: Any, bundle: SeedBundle) -> None:
    """Before the lessons are written: a lesson cut out of another (`split_from`) takes over its
    words, cards and practice answers as the SAME rows (their ids stay, and so do the learners'
    schedules, mistakes and answers). Runs once: when the old lesson no longer holds them, there is
    nothing to move. The new lesson's row is created here if it is not there yet; the regular sync
    fills in the rest."""
    from sqlalchemy import select, update

    from app.models import (
        GrammarPoint,
        Lesson,
        LessonEssayCheck,
        LessonExerciseResult,
        VocabItem,
    )

    for resolved in bundle.lessons:
        seed = resolved.seed
        if not seed.split_from:
            continue
        new = db.execute(select(Lesson).where(Lesson.slug == seed.slug)).scalar_one_or_none()
        if new is not None and new.content_hash == resolved.content_hash:
            continue  # written already (the move happened then): one SELECT, as for any unchanged lesson
        old = db.execute(select(Lesson).where(Lesson.slug == seed.split_from)).scalar_one_or_none()
        if old is None:
            continue
        words = [v.headword for v in seed.vocab]
        patterns = [g.pattern for g in seed.grammar]
        exercises = set(seed.exercise_ids)
        held = db.execute(
            select(VocabItem.id).where(VocabItem.lesson_id == old.id, VocabItem.headword.in_(words)).limit(1)
        ).first() or db.execute(
            select(GrammarPoint.id).where(GrammarPoint.lesson_id == old.id, GrammarPoint.pattern.in_(patterns)).limit(1)
        ).first() or db.execute(
            select(LessonExerciseResult.id)
            .where(LessonExerciseResult.lesson_id == old.id, LessonExerciseResult.exercise_id.in_(exercises))
            .limit(1)
        ).first()
        if not held:
            continue
        if new is None:
            # a placeholder hash (the column is unique): the regular sync below writes the whole lesson
            new = Lesson(slug=seed.slug, content_hash=f"moving:{seed.slug}", title=seed.title, level=seed.level, content="")
            db.add(new)
            db.flush()
        if words:
            db.execute(update(VocabItem).where(VocabItem.lesson_id == old.id, VocabItem.headword.in_(words)).values(lesson_id=new.id))
        if patterns:
            db.execute(
                update(GrammarPoint).where(GrammarPoint.lesson_id == old.id, GrammarPoint.pattern.in_(patterns)).values(lesson_id=new.id)
            )
        if exercises:
            for model in (LessonExerciseResult, LessonEssayCheck):
                db.execute(
                    update(model).where(model.lesson_id == old.id, model.exercise_id.in_(exercises)).values(lesson_id=new.id)
                )
        # both lessons are written again by the sync
        old.content_hash = f"moving:{old.slug}"
        db.flush()


def run_startup_sync() -> dict[str, str]:
    """Called once when the API starts. Takes a Postgres advisory lock so two
    instances starting together do not both write; the one that does not get the
    lock skips (the other is doing the same work)."""
    from sqlalchemy import create_engine, text
    from sqlalchemy.orm import Session

    from app.core.config import settings

    engine = create_engine(settings.SYNC_DATABASE_URL, pool_pre_ping=True)
    try:
        with Session(engine) as db:
            if not db.execute(text("SELECT pg_try_advisory_lock(7351005)")).scalar():
                return {}
            try:
                report = sync_lessons(db)
                from app.services import (
                    topik_bank,  # late: the bank file is read only here
                )

                bank = topik_bank.sync_bank(db)
                if bank:
                    report["topik_bank"] = ", ".join(f"{k}={v}" for k, v in bank.items())
                return report
            finally:
                db.execute(text("SELECT pg_advisory_unlock(7351005)"))
                db.commit()
    finally:
        engine.dispose()


def _check_file(path: Path) -> int:
    """Validate ONE seed file (a lesson, or a skill bank / overview / extension) on its own."""
    try:
        data = _read(path)
        if path.parent.name == "lessons":
            seed = LessonSeed.model_validate(data)
            print(f"OK lesson {seed.slug}: vocab={len(seed.vocab)} grammar={len(seed.grammar)} "
                  f"notes={len(seed.notes)} exercise_ids={seed.exercise_ids}")
        elif path.stem == "overview":
            Overview.model_validate(data)
            print("OK overview")
        elif path.stem == "extension":
            Extension.model_validate(data)
            print("OK extension")
        else:
            bank = SkillBank.model_validate(data)
            problems = []
            for raw in bank.items:
                try:
                    ex = _validate_exercise(raw, bank.skill)
                    print(f"  ok {ex['id']:8} {ex['type']:18} questions={len(_question_ids(ex))}")
                except (ValidationError, ValueError) as exc:
                    problems.append(f"{raw.get('id', '?')}: {exc}")
            for p in problems:
                print("PROBLEM:", p)
            return 1 if problems else 0
    except (ValidationError, ValueError) as exc:
        print("PROBLEM:", exc)
        return 1
    return 0


