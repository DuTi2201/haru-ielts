"""Lesson seed (lesson-v5): the lessons are written once, checked by a person and
kept as JSON in the repo — never generated by a model from an upload.

    app/seed/lessons/*.json       one file per lesson: vocabulary, grammar, notes and
                                  the ids of the practice items that belong to it
    app/seed/exercises/*.json     the practice bank, one file per skill (listening,
                                  reading, writing, speaking) + overview + extension
    app/seed/exercises/<bank>/    another bank of the same shape (one per topic whose
                                  practice set has its own guides); a lesson names it
                                  with `bank`, "" is the folder above

`load_all()` reads and VALIDATES everything (a typo in a file is an error here, not
a blank screen in the app) and resolves each lesson's exercise ids into the full
practice set. `sync_lessons(db)` then writes it to content.lesson / vocab_item /
grammar_point, idempotently: a lesson whose content hash did not change is left
alone; a changed one is updated IN PLACE (vocab by headword, grammar by pattern), so
the ids — and with them every learner's review schedule — survive an edit.

Everything the learner sees is Vietnamese + Korean; nothing in these files is an
API key or a secret.

Run `python -m app.services.lesson_seed --check` to validate the files.
"""
