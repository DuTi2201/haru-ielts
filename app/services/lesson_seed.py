class ClozeStimulus(_M):
    kind: Literal["cloze"]
    text: str  # the gap is "( )"

    @field_validator("text")
    @classmethod
    def _has_gap(cls, v: str) -> str:
        if "( )" not in v:
            raise ValueError('a cloze text needs a "( )" gap')
        return v


class UnderlineStimulus(_M):
    kind: Literal["underline"]
    text: str  # the underlined part sits between 【 and 】

    @field_validator("text")
    @classmethod
    def _has_mark(cls, v: str) -> str:
        if "【" not in v or "】" not in v:
            raise ValueError("an underline text needs 【…】 around the underlined part")
        return v


