class HangulSeed(_M):
    intro_vi: str = Field(max_length=300)
    done_vi: str = Field(max_length=200)
    parts: list[HangulPart] = Field(min_length=5, max_length=5)

    @model_validator(mode="after")
    def _words_use_what_was_taught(self) -> "HangulSeed":
        initial: set[str] = {"ㅇ"}
        medial: set[str] = set()
        finals = False
        for part in self.parts:
            for g in part.groups:
                for l in g.letters:
                    (medial if l.jamo in JAMO_MEDIAL else initial).add(l.jamo)
            if part.sort or part.build and any(jamo_of(s) and jamo_of(s)[2] for s in part.build):
                finals = True
            for w in part.words:
                for ch in w.ko.replace(" ", ""):
                    j = jamo_of(ch)
                    if j is None:
                        raise ValueError(f"{part.id}: {w.ko!r} has a character that is not a Hangul syllable")
                    a, m, f = j
                    if a not in initial or m not in medial or (f and not finals):
                        raise ValueError(f"{part.id}: {w.ko!r} uses {ch} before its letters are taught")
        return self


