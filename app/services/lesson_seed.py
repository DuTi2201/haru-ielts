# ---------------------------------------------------------------- shared bits --
class Table(_M):
    header: list[str]
    rows: list[list[str]]

    @model_validator(mode="after")
    def _rectangular(self) -> "Table":
        for row in self.rows:
            if len(row) != len(self.header):
                raise ValueError(f"table row {row!r} has {len(row)} cells, header has {len(self.header)}")
        return self


class Series(_M):
    name: str
    values: list[float]


class Chart(_M):
    type: Literal["bar", "line", "pie"]
    title_vi: str | None = None
    unit: str | None = None
    categories: list[str]
    series: list[Series] = Field(min_length=1)

    @model_validator(mode="after")
    def _aligned(self) -> "Chart":
        for s in self.series:
            if len(s.values) != len(self.categories):
                raise ValueError(f"series {s.name!r} has {len(s.values)} values for {len(self.categories)} categories")
        return self


class DataBlock(_M):
    """A chart or a table with its caption."""

    title_vi: str | None = None
    note_vi: str | None = None
    chart: Chart | None = None
    table: Table | None = None

    @model_validator(mode="after")
    def _one_of(self) -> "DataBlock":
        if (self.chart is None) == (self.table is None):
            raise ValueError("a data block needs exactly one of chart / table")
        return self


class Scene(_M):
    """A picture drawn from icons for now: what the picture shows, in words."""

    caption_vi: str
    icons: list[str] = Field(min_length=1, max_length=4)
    image_prompt: str | None = None  # for a generated picture later (English, one sentence)

    @field_validator("icons")
    @classmethod
    def _known_icons(cls, icons: list[str]) -> list[str]:
        unknown = [i for i in icons if i not in SCENE_ICONS]
        if unknown:
            raise ValueError(f"unknown scene icon(s) {unknown}; allowed: see SCENE_ICONS")
        return icons


class GuideBlock(_M):
    """A titled block of advice: paragraph, bullets and/or a table."""

    title_vi: str
    body_vi: str | None = None
    bullets_vi: list[str] = []
    table: Table | None = None


